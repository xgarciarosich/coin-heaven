//! Encrypted storage.
//!
//! One process-wide connection behind a mutex, deliberately. A pool would mean
//! re-keying every new connection and re-asserting `PRAGMA foreign_keys`
//! (which is per-connection, not per-database) on each one — more moving parts
//! for no benefit in a single-user desktop app whose queries are sub-millisecond.

